import 'dart:async';
import 'dart:convert';
import 'dart:io';
import 'dart:math';

import 'package:flauncher/flauncher_channel.dart';
import 'package:flauncher/gradients.dart';
import 'package:flauncher/models/yama_settings.dart';
import 'package:flauncher/providers/settings_service.dart';
import 'package:flutter/painting.dart';
import 'package:flutter/foundation.dart';
import 'package:image_picker/image_picker.dart';
import 'package:path_provider/path_provider.dart';

class WallpaperService extends ChangeNotifier {
  final FLauncherChannel _fLauncherChannel;
  final SettingsService _settingsService;
  final Random _random = Random();

  File? _wallpaperFile;
  Directory? _slideshowDirectory;

  ImageProvider? _wallpaper;

  List<File> _slides = [];
  List<int> _slideOrder = [];
  int _slidePosition = 0;
  int _slideCounter = 0;
  Timer? _slideTimer;
  int _timerInterval = 0;
  WallpaperMode? _lastMode;

  // Reddit and web-link wallpapers
  List<String> _remote = [];
  int _remotePosition = 0;
  String _remoteSource = "";
  bool _remoteLoading = false;
  String? _remoteError;
  DateTime? _remoteFetchedAt;

  /// The single picked picture, used in [WallpaperMode.image].
  ImageProvider? get wallpaper => _wallpaper;

  WallpaperMode get mode => _settingsService.wallpaperMode;

  /// Number of pictures in the slideshow.
  int get slideCount => _slides.length;

  /// Current slideshow picture, or null when there is none.
  ImageProvider? get currentSlide =>
      _slides.isEmpty ? null : FileImage(_slides[_slideOrder[_slidePosition % _slideOrder.length]]);

  bool get remoteLoading => _remoteLoading;

  /// Why Reddit or web wallpapers couldn't load, or null.
  String? get remoteError => _remoteError;

  int get remoteCount => _remote.length;

  /// Picture to show for the slideshow, Reddit and web modes (null = none yet).
  ImageProvider? get currentImage {
    switch (mode) {
      case WallpaperMode.slideshow:
        return currentSlide;
      case WallpaperMode.reddit:
      case WallpaperMode.web:
        if (_remote.isEmpty) {
          return null;
        }
        String url = _remote[_remotePosition % _remote.length];
        // A single web link may be regenerated by a tool (e.g. a TMDB
        // wallpaper script), so ask for a fresh copy on every change.
        if (mode == WallpaperMode.web && _remote.length == 1) {
          url += (url.contains("?") ? "&" : "?") + "yama=$_slideCounter";
        }
        return NetworkImage(url, headers: const {"User-Agent": _userAgent});
      default:
        return null;
    }
  }

  /// Changes every time the slideshow advances; used to animate transitions.
  int get slideCounter => _slideCounter;

  Color get solidColor => Color(_settingsService.wallpaperSolidColor);

  FLauncherGradient get gradient => FLauncherGradients.all.firstWhere(
        (gradient) => gradient.uuid == _settingsService.gradientUuid,
        orElse: () => FLauncherGradients.greatWhale,
      );

  WallpaperService(this._fLauncherChannel, this._settingsService) :
    _wallpaper = null
  {
    _settingsService.addListener(_onSettingsChanged);
    _init();
  }

  Future<void> _init() async {
    final directory = await getApplicationDocumentsDirectory();
    _wallpaperFile = File("${directory.path}/wallpaper");
    _slideshowDirectory = Directory("${directory.path}/slideshow");

    if (await _wallpaperFile!.exists()) {
      _wallpaper = FileImage(_wallpaperFile!);
    }
    await _loadSlides();
    _onSettingsChanged();
    notifyListeners();
  }

  @override
  void dispose() {
    _slideTimer?.cancel();
    _settingsService.removeListener(_onSettingsChanged);
    super.dispose();
  }

  void _onSettingsChanged() {
    final WallpaperMode currentMode = mode;
    final int interval = _settingsService.slideshowInterval;
    _ensureRemote(currentMode);
    final bool slideshowActive = (currentMode == WallpaperMode.slideshow && _slides.length > 1) ||
        (currentMode == WallpaperMode.reddit && _remote.length > 1) ||
        (currentMode == WallpaperMode.web && _remote.isNotEmpty);

    if (!slideshowActive) {
      _slideTimer?.cancel();
      _slideTimer = null;
      _timerInterval = 0;
    }
    else if (_slideTimer == null || interval != _timerInterval) {
      _restartTimer();
    }

    if (_lastMode != currentMode) {
      _lastMode = currentMode;
      notifyListeners();
    }
  }

  void _restartTimer() {
    _slideTimer?.cancel();
    _timerInterval = max(15, _settingsService.slideshowInterval);
    _slideTimer = Timer.periodic(Duration(seconds: _timerInterval), (_) => nextWallpaper());
  }

  Future<void> _loadSlides() async {
    final Directory? directory = _slideshowDirectory;
    if (directory == null || !await directory.exists()) {
      _slides = [];
    }
    else {
      _slides = directory.listSync().whereType<File>().toList()
        ..sort((a, b) => a.path.compareTo(b.path));
    }
    _shuffle();
  }

  /// A fresh random order, so pictures don't repeat until all were shown.
  void _shuffle() {
    final int previous = _slideOrder.isEmpty ? -1 : _slideOrder[_slidePosition % _slideOrder.length];
    _slideOrder = List<int>.generate(_slides.length, (index) => index)..shuffle(_random);
    if (_slideOrder.length > 1 && _slideOrder.first == previous) {
      _slideOrder.add(_slideOrder.removeAt(0));
    }
    _slidePosition = 0;
  }

  /// Shows the next slideshow picture now (also bound to Play/Pause).
  void nextWallpaper() {
    switch (mode) {
      case WallpaperMode.slideshow:
        if (_slides.length < 2) {
          return;
        }
        _slidePosition++;
        if (_slidePosition >= _slideOrder.length) {
          _shuffle();
        }
      case WallpaperMode.reddit:
        // Refresh the post list every few hours so new posts show up.
        final DateTime? fetched = _remoteFetchedAt;
        if (fetched != null && DateTime.now().difference(fetched) > const Duration(hours: 3)) {
          _remoteSource = "";
          _ensureRemote(WallpaperMode.reddit);
        }
        if (_remote.length < 2) {
          return;
        }
        _remotePosition++;
        if (_remotePosition >= _remote.length) {
          _remote.shuffle(_random);
          _remotePosition = 0;
        }
      case WallpaperMode.web:
        if (_remote.isEmpty) {
          return;
        }
        _remotePosition++;
      default:
        return;
    }
    _slideCounter++;
    notifyListeners();
  }

  /// Retries Reddit / web wallpapers (used by the settings page).
  void reloadRemote() {
    _remoteSource = "";
    _onSettingsChanged();
    notifyListeners();
  }

  void _ensureRemote(WallpaperMode currentMode) {
    if (currentMode == WallpaperMode.web) {
      final List<String> urls = _splitList(_settingsService.webImageUrls)
          .where((url) => url.startsWith("http://") || url.startsWith("https://"))
          .toList();
      final String source = "web:${urls.join(" ")}";
      if (source != _remoteSource) {
        _remoteSource = source;
        _remote = urls;
        _remotePosition = 0;
        _remoteError = urls.isEmpty ? "Add at least one image link (starting with https://)." : null;
        _slideCounter++;
      }
      return;
    }

    if (currentMode != WallpaperMode.reddit) {
      return;
    }
    final List<String> subreddits = _splitList(_settingsService.redditSubreddits)
        .map((name) => name.replaceFirst(RegExp(r"^/?r/", caseSensitive: false), ""))
        .where((name) => RegExp(r"^[A-Za-z0-9_]{2,21}$").hasMatch(name))
        .toList();
    final String source = "reddit:${subreddits.join("+").toLowerCase()}";
    if (source == _remoteSource || _remoteLoading) {
      return;
    }
    _remoteSource = source;
    if (subreddits.isEmpty) {
      _remote = [];
      _remoteError = "Add at least one subreddit name.";
      return;
    }
    _fetchReddit(subreddits);
  }

  static List<String> _splitList(String text) =>
      text.split(RegExp(r"[\s,;]+")).map((part) => part.trim()).where((part) => part.isNotEmpty).toList();

  static const String _userAgent = "android:app.yama.launcher:1.0 (YaMa Launcher wallpaper)";

  Future<void> _fetchReddit(List<String> subreddits) async {
    _remoteLoading = true;
    _remoteError = null;
    notifyListeners();

    final String path = "/r/${subreddits.join("+")}/hot.json?limit=100&raw_json=1";
    List<String> found = [];
    String? error;
    for (final String host in const ["www.reddit.com", "old.reddit.com", "api.reddit.com"]) {
      try {
        found = await _readRedditListing(Uri.parse("https://$host$path"));
        error = null;
        break;
      } catch (e) {
        error = "Couldn't reach Reddit ($e).";
      }
    }

    _remoteLoading = false;
    _remoteFetchedAt = DateTime.now();
    if (found.isEmpty) {
      _remoteError = error ?? "No wide pictures found in those subreddits.";
    } else {
      found.shuffle(_random);
      _remote = found;
      _remotePosition = 0;
      _remoteError = null;
      _slideCounter++;
    }
    _onSettingsChanged();
    notifyListeners();
  }

  /// Reads a subreddit listing and keeps landscape pictures at least 1280px wide.
  Future<List<String>> _readRedditListing(Uri uri) async {
    final HttpClient client = HttpClient()..connectionTimeout = const Duration(seconds: 15);
    try {
      final HttpClientRequest request = await client.getUrl(uri);
      request.headers.set(HttpHeaders.userAgentHeader, _userAgent);
      request.headers.set(HttpHeaders.acceptHeader, "application/json");
      final HttpClientResponse response = await request.close().timeout(const Duration(seconds: 30));
      if (response.statusCode < 200 || response.statusCode >= 300) {
        throw HttpException("HTTP ${response.statusCode}");
      }
      final String body = await response.transform(utf8.decoder).join();
      final Object? json = jsonDecode(body);
      final List<String> urls = [];
      final Object? children = json is Map ? (json["data"] is Map ? json["data"]["children"] : null) : null;
      if (children is! List) {
        return urls;
      }
      for (final Object? child in children) {
        if (child is! Map || child["data"] is! Map) {
          continue;
        }
        final Map post = child["data"] as Map;
        if (post["over_18"] == true || post["stickied"] == true) {
          continue;
        }
        final String? url = _pictureFromPost(post);
        if (url != null) {
          urls.add(url);
        }
      }
      return urls;
    } finally {
      client.close(force: true);
    }
  }

  static String? _pictureFromPost(Map post) {
    bool wide(num? width, num? height) =>
        width != null && height != null && width >= 1280 && width > height * 1.2;

    // Single picture posts: use the full-size source from the preview data.
    final Object? preview = post["preview"];
    if (preview is Map && preview["images"] is List && (preview["images"] as List).isNotEmpty) {
      final Object? first = (preview["images"] as List).first;
      final Object? source = first is Map ? first["source"] : null;
      if (source is Map && wide(source["width"] as num?, source["height"] as num?)) {
        final String direct = (post["url"] ?? "").toString();
        if (RegExp(r"\.(jpe?g|png|webp)$", caseSensitive: false).hasMatch(direct)) {
          return direct;
        }
        final Object? sourceUrl = source["url"];
        if (sourceUrl is String && sourceUrl.startsWith("http")) {
          return sourceUrl;
        }
      }
    }

    // Gallery posts: take the first wide picture.
    final Object? metadata = post["media_metadata"];
    if (post["is_gallery"] == true && metadata is Map) {
      for (final Object? item in metadata.values) {
        final Object? s = item is Map ? item["s"] : null;
        if (s is Map && s["u"] is String && wide(s["x"] as num?, s["y"] as num?)) {
          return s["u"] as String;
        }
      }
    }
    return null;
  }

  Future<void> _ensureFileExplorer() async {
    if (!await _fLauncherChannel.checkForGetContentAvailability()) {
      throw NoFileExplorerException();
    }
  }

  Future<void> pickWallpaper() async {
    await _ensureFileExplorer();

    final imagePicker = ImagePicker();
    final pickedFile = await imagePicker.pickImage(source: ImageSource.gallery);
    if (pickedFile != null) {
      Uint8List bytes = await pickedFile.readAsBytes();
      await _wallpaperFile!.writeAsBytes(bytes);

      _wallpaper = MemoryImage(bytes);
      await _settingsService.setValue(YamaKeys.wallpaperMode, WallpaperMode.image);
      notifyListeners();
    }
  }

  /// Adds pictures to the slideshow and switches to slideshow mode.
  Future<int> addSlideshowPictures() async {
    await _ensureFileExplorer();

    final List<XFile> picked = await ImagePicker().pickMultiImage();
    if (picked.isEmpty) {
      return 0;
    }

    final Directory directory = _slideshowDirectory!;
    if (!await directory.exists()) {
      await directory.create(recursive: true);
    }
    final int stamp = DateTime.now().millisecondsSinceEpoch;
    for (int i = 0; i < picked.length; i++) {
      final Uint8List bytes = await picked[i].readAsBytes();
      await File("${directory.path}/slide_${stamp}_$i").writeAsBytes(bytes);
    }

    await _loadSlides();
    _slideCounter++;
    await _settingsService.setValue(YamaKeys.wallpaperMode, WallpaperMode.slideshow);
    _onSettingsChanged();
    notifyListeners();
    return picked.length;
  }

  Future<void> clearSlideshow() async {
    final Directory? directory = _slideshowDirectory;
    if (directory != null && await directory.exists()) {
      await directory.delete(recursive: true);
    }
    await _loadSlides();
    if (mode == WallpaperMode.slideshow) {
      await _settingsService.setValue(YamaKeys.wallpaperMode, WallpaperMode.gradient);
    }
    _onSettingsChanged();
    notifyListeners();
  }

  Future<void> setSolidColor(Color color) async {
    await _settingsService.setValue(YamaKeys.wallpaperSolidColor, color.value);
    await _settingsService.setValue(YamaKeys.wallpaperMode, WallpaperMode.solid);
    notifyListeners();
  }

  Future<void> setGradient(FLauncherGradient fLauncherGradient) async {
    final File? file = _wallpaperFile;
    if (file != null && await file.exists()) {
      await file.delete();
    }
    _wallpaper = null;

    await _settingsService.setGradientUuid(fLauncherGradient.uuid);
    await _settingsService.setValue(YamaKeys.wallpaperMode, WallpaperMode.gradient);
    notifyListeners();
  }

  /// Switches back to an already chosen picture or slideshow, if available.
  Future<void> useMode(WallpaperMode newMode) async {
    await _settingsService.setValue(YamaKeys.wallpaperMode, newMode);
    _onSettingsChanged();
    notifyListeners();
  }
}

class NoFileExplorerException implements Exception {}

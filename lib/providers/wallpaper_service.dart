class WallpaperService extends ChangeNotifier {
  final FLauncherChannel _fLauncherChannel;
  final SettingsService _settingsService;
  final Random _random = Random();

  File? _wallpaperFile;
  Directory? _slideshowDirectory;

  /// Folder in YaMa's own storage that ADB (or a file manager) can copy
  /// pictures into; they join the slideshow. No permission needed.
  Directory? _deviceFolder;

  /// Full path of [_deviceFolder], shown on the settings page.
  String? get deviceFolderPath => _deviceFolder?.path;

  ImageProvider? _wallpaper;

  List<File> _slides = [];
  List<int> _slideOrder = [];
  int _slidePosition = 0;
  int _slideCounter = 0;
  Timer? _slideTimer;
  int _timerInterval = 0;
  WallpaperMode? _lastMode;

  // Reddit and web-link wallpapers
  List<String> _remote = [];
  int _remotePosition = 0;
  String _remoteSource = "";
  bool _remoteLoading = false;
  String? _remoteError;
  DateTime? _remoteFetchedAt;

  /// The single picked picture, used in [WallpaperMode.image].
  ImageProvider? get wallpaper => _wallpaper;

  WallpaperMode get mode => _settingsService.wallpaperMode;

  /// Number of pictures in the slideshow.
  int get slideCount => _slides.length;

  /// Current slideshow picture, or null when there is none.
  ImageProvider? get currentSlide =>
      _slides.isEmpty ? null : FileImage(_slides[_slideOrder[_slidePosition % _slideOrder.length]]);

  bool get remoteLoading => _remoteLoading;

  /// Why Reddit or web wallpapers couldn't load, or null.
  String? get remoteError => _remoteError;

  int get remoteCount => _remote.length;

  /// Picture to show for the slideshow, Reddit and web modes (null = none yet).
  ImageProvider? get currentImage {
    switch (mode) {
      case WallpaperMode.slideshow:
        return currentSlide;
      case WallpaperMode.reddit:
      case WallpaperMode.web:
        if (_remote.isEmpty) {
          return null;
        }
        String url = _remote[_remotePosition % _remote.length];
        // A single web link may be regenerated by a tool (e.g. a TMDB
        // wallpaper script), so ask for a fresh copy on every change.
        if (mode == WallpaperMode.web && _remote.length == 1) {
          url += (url.contains("?") ? "&" : "?") + "yama=$_slideCounter";
        }
        return NetworkImage(url, headers: const {"User-Agent": _userAgent});
      default:
        return null;
    }
  }

  /// Changes every time the slideshow advances; used to animate transitions.
  int get slideCounter => _slideCounter;

  Color get solidColor => Color(_settingsService.wallpaperSolidColor);

  FLauncherGradient get gradient => FLauncherGradients.all.firstWhere(
        (gradient) => gradient.uuid == _settingsService.gradientUuid,
        orElse: () => FLauncherGradients.greatWhale,
      );

  Timer? _exportTimer;

  // The screensaver's own pictures: copies kept by YaMa, plus a folder ADB
  // or a file manager can copy into (Android/data/app.yama.launcher/files/screensaver).
  Directory? _screensaverDirectory;
  Directory? _screensaverDeviceFolder;
  List<File> _screensaverPictures = [];

  int get screensaverPictureCount => _screensaverPictures.length;
  String? get screensaverFolderPath => _screensaverDeviceFolder?.path;

  static final RegExp _pictureName = RegExp(r"\.(jpe?g|png|webp|gif)$", caseSensitive: false);

  Future<void> reloadScreensaverPictures() async {
    final List<File> files = [];
    final Directory? own = _screensaverDirectory;
    if (own != null && await own.exists()) {
      files.addAll(own.listSync().whereType<File>());
    }
    final Directory? device = _screensaverDeviceFolder;
    if (device != null && await device.exists()) {
      files.addAll(device.listSync(recursive: true).whereType<File>().where((f) => _pictureName.hasMatch(f.path)));
    }
    _screensaverPictures = files..sort((a, b) => a.path.compareTo(b.path));
    notifyListeners();
  }

  Future<Directory> _ownScreensaverDirectory() async {
    final Directory directory = _screensaverDirectory!;
    if (!await directory.exists()) await directory.create(recursive: true);
    return directory;
  }

  /// Copies one picture (chosen in YaMa's file browser) into the screensaver.
  Future<void> addScreensaverPicture(String path) async {
    final Directory directory = await _ownScreensaverDirectory();
    await File(path).copy("${directory.path}/pic_${DateTime.now().millisecondsSinceEpoch}");
    await _useOwnScreensaverPictures();
  }

  /// Copies every picture in a folder into the screensaver.
  Future<int> addScreensaverFolder(String folderPath) async {
    final Directory directory = await _ownScreensaverDirectory();
    final List<File> pictures =
        Directory(folderPath).listSync().whereType<File>().where((f) => _pictureName.hasMatch(f.path)).toList();
    final int stamp = DateTime.now().millisecondsSinceEpoch;
    for (int i = 0; i < pictures.length; i++) {
      await pictures[i].copy("${directory.path}/pic_${stamp}_$i");
    }
    await _useOwnScreensaverPictures();
    return pictures.length;
  }

  /// Picks pictures with another app (the Android picker or a file explorer).
  Future<int> addScreensaverPicturesWithPicker() async {
    await _ensureFileExplorer();
    final List<XFile> picked = await ImagePicker().pickMultiImage();
    if (picked.isEmpty) return 0;
    final Directory directory = await _ownScreensaverDirectory();
    final int stamp = DateTime.now().millisecondsSinceEpoch;
    for (int i = 0; i < picked.length; i++) {
      await File("${directory.path}/pic_${stamp}_$i").writeAsBytes(await picked[i].readAsBytes(), flush: true);
    }
    await _useOwnScreensaverPictures();
    return picked.length;
  }

  Future<void> clearScreensaverPictures() async {
    final Directory? directory = _screensaverDirectory;
    if (directory != null && await directory.exists()) {
      await directory.delete(recursive: true);
    }
    await reloadScreensaverPictures();
  }

  Future<void> _useOwnScreensaverPictures() async {
    await reloadScreensaverPictures();
    await _settingsService.setValue(YamaKeys.screensaverSource, "own");
  }

  /// Opens YaMa's screensaver straight away, after saving its settings.
  Future<void> previewScreensaver() async {
    _exportTimer?.cancel();
    await _exportScreensaver();
    await _fLauncherChannel.previewScreensaver();
  }

  @override
  void notifyListeners() {
    super.notifyListeners();
    _scheduleExport();
  }

  /// The screensaver is native Android code; it reads what to show from
  /// screensaver.json, kept in step with the launcher's look.
  void _scheduleExport() {
    _exportTimer?.cancel();
    _exportTimer = Timer(const Duration(seconds: 2), _exportScreensaver);
  }

  Future<void> _exportScreensaver() async {
    try {
      final Directory directory = await getApplicationDocumentsDirectory();
      final SettingsService s = _settingsService;
      final List<String> local = [];
      final List<String> remote = [];
      if (s.screensaverOwnPictures) {
        local.addAll(_screensaverPictures.map((file) => file.path));
      } else switch (mode) {
        case WallpaperMode.slideshow:
          local.addAll(_slides.map((file) => file.path));
        case WallpaperMode.image:
          final File? file = _wallpaperFile;
          if (file != null && await file.exists()) local.add(file.path);
        case WallpaperMode.reddit:
        case WallpaperMode.web:
          remote.addAll(_remote);
        case WallpaperMode.gradient:
        case WallpaperMode.solid:
          break;
      }
      final List<int> colors = mode == WallpaperMode.solid
          ? [s.wallpaperSolidColor]
          : (gradient.gradient is LinearGradient
              ? (gradient.gradient as LinearGradient).colors.map((c) => c.value).toList()
              : <int>[]);
      final Map<String, Object> config = {
        "local": local,
        "remote": remote.take(200).toList(),
        "colors": colors,
        "interval": s.screensaverInterval > 0 ? s.screensaverInterval : s.slideshowInterval,
        "transition": s.slideshowTransition.name,
        "dim": s.wallpaperDim,
        "shadow": s.wallpaperShadow,
        "font": s.fontFamily,
        "clock": {
          "showTime": s.showTimeInStatusBar,
          "showDate": s.showDateInStatusBar,
          "twoLines": s.clockTwoLines,
          "color": s.clockColor,
          "size": s.clockSize,
          "shadow": s.clockShadow,
          "timeFormat": s.timeFormat,
          "dateFormat": s.dateFormat,
        },
      };
      await File("${directory.path}/screensaver.json").writeAsString(jsonEncode(config), flush: true);
    } catch (_) {
      // The screensaver falls back to defaults if this can't be written.
    }
  }

  WallpaperService(this._fLauncherChannel, this._settingsService) :
    _wallpaper = null
  {
    _settingsService.addListener(_onSettingsChanged);
    _init();
  }

  Future<void> _init() async {
    final directory = await getApplicationDocumentsDirectory();
    _wallpaperFile = File("${directory.path}/wallpaper");
    _slideshowDirectory = Directory("${directory.path}/slideshow");
    _screensaverDirectory = Directory("${directory.path}/screensaver_pictures");
    try {
      final Directory? external = await getExternalStorageDirectory();
      if (external != null) {
        _deviceFolder = Directory("${external.path}/wallpapers");
        await _deviceFolder!.create(recursive: true);
        _screensaverDeviceFolder = Directory("${external.path}/screensaver");
        await _screensaverDeviceFolder!.create(recursive: true);
      }
    } catch (_) {
      _deviceFolder = null;
    }
    await reloadScreensaverPictures();

    if (await _wallpaperFile!.exists()) {
      _wallpaper = FileImage(_wallpaperFile!);
    }
    await _loadSlides();
    _onSettingsChanged();
    notifyListeners();
  }

  @override
  void dispose() {
    _exportTimer?.cancel();
    _slideTimer?.cancel();
    _settingsService.removeListener(_onSettingsChanged);
    super.dispose();
  }

  void _onSettingsChanged() {
    _scheduleExport();
    final WallpaperMode currentMode = mode;
    final int interval = _settingsService.slideshowInterval;
    _ensureRemote(currentMode);
    final bool slideshowActive = (currentMode == WallpaperMode.slideshow && _slides.length > 1) ||
        (currentMode == WallpaperMode.reddit && _remote.length > 1) ||
        (currentMode == WallpaperMode.web && _remote.isNotEmpty);

    if (!slideshowActive) {
      _slideTimer?.cancel();
      _slideTimer = null;
      _timerInterval = 0;
    }
    else if (_slideTimer == null || interval != _timerInterval) {
      _restartTimer();
    }

    if (_lastMode != currentMode) {
      _lastMode = currentMode;
      notifyListeners();
    }
  }

  void _restartTimer() {
    _slideTimer?.cancel();
    _timerInterval = max(15, _settingsService.slideshowInterval);
    _slideTimer = Timer.periodic(Duration(seconds: _timerInterval), (_) => nextWallpaper());
  }

  Future<void> _loadSlides() async {
    final List<File> files = [];
    for (final Directory? directory in [_slideshowDirectory, _deviceFolder]) {
      if (directory != null && await directory.exists()) {
        files.addAll(directory
            .listSync(recursive: true)
            .whereType<File>()
            .where((file) => directory == _slideshowDirectory ||
                RegExp(r"\.(jpe?g|png|webp|gif)$", caseSensitive: false).hasMatch(file.path)));
      }
    }
    _slides = files..sort((a, b) => a.path.compareTo(b.path));
    _shuffle();
  }

  /// Re-reads the slideshow folders (after copying new pictures with ADB).
  Future<void> reloadSlides() async {
    await _loadSlides();
    _slideCounter++;
    _onSettingsChanged();
    notifyListeners();
  }

  /// A fresh random order, so pictures don't repeat until all were shown.
  void _shuffle() {
    final int previous = _slideOrder.isEmpty ? -1 : _slideOrder[_slidePosition % _slideOrder.length];
    _slideOrder = List<int>.generate(_slides.length, (index) => index)..shuffle(_random);
    if (_slideOrder.length > 1 && _slideOrder.first == previous) {
      _slideOrder.add(_slideOrder.removeAt(0));
    }
    _slidePosition = 0;
  }

  /// Shows the next slideshow picture now (also bound to Play/Pause).
  void nextWallpaper() {
    switch (mode) {
      case WallpaperMode.slideshow:
        if (_slides.length < 2) {
          return;
        }
        _slidePosition++;
        if (_slidePosition >= _slideOrder.length) {
          _shuffle();
        }
      case WallpaperMode.reddit:
        // Refresh the post list every few hours so new posts show up.
        final DateTime? fetched = _remoteFetchedAt;
        if (fetched != null && DateTime.now().difference(fetched) > const Duration(hours: 3)) {
          _remoteSource = "";
          _ensureRemote(WallpaperMode.reddit);
        }
        if (_remote.length < 2) {
          return;
        }
        _remotePosition++;
        if (_remotePosition >= _remote.length) {
          _remote.shuffle(_random);
          _remotePosition = 0;
        }
      case WallpaperMode.web:
        // Folder links are re-read every hour so newly generated pictures appear.
        final DateTime? fetchedWeb = _remoteFetchedAt;
        if (fetchedWeb != null && DateTime.now().difference(fetchedWeb) > const Duration(hours: 1) &&
            _splitList(_settingsService.webImageUrls).any((url) => url.endsWith("/"))) {
          _remoteSource = "";
          _ensureRemote(WallpaperMode.web);
        }
        if (_remote.isEmpty) {
          return;
        }
        _remotePosition++;
      default:
        return;
    }
    _slideCounter++;
    notifyListeners();
  }

  /// Retries Reddit / web wallpapers (used by the settings page).
  void reloadRemote() {
    _remoteSource = "";
    _onSettingsChanged();
    notifyListeners();
  }

  void _ensureRemote(WallpaperMode currentMode) {
    if (currentMode == WallpaperMode.web) {
      final List<String> urls = _splitList(_settingsService.webImageUrls)
          .where((url) => url.startsWith("http://") || url.startsWith("https://"))
          .toList();
      final String source = "web:${urls.join(" ")}";
      if (source != _remoteSource && !_remoteLoading) {
        _remoteSource = source;
        if (urls.isEmpty) {
          _remote = [];
          _remoteError = "Add at least one image link (starting with http:// or https://).";
        } else if (urls.any((url) => url.endsWith("/"))) {
          _resolveWebLinks(urls);
        } else {
          _remote = urls;
          _remotePosition = 0;
          _remoteError = null;
          _slideCounter++;
        }
      }
      return;
    }

    if (currentMode != WallpaperMode.reddit) {
      return;
    }
    final List<String> subreddits = _splitList(_settingsService.redditSubreddits)
        .map((name) => name.replaceFirst(RegExp(r"^/?r/", caseSensitive: false), ""))
        .where((name) => RegExp(r"^[A-Za-z0-9_]{2,21}$").hasMatch(name))
        .toList();
    final String source = "reddit:${subreddits.join("+").toLowerCase()}";
    if (source == _remoteSource || _remoteLoading) {
      return;
    }
    _remoteSource = source;
    if (subreddits.isEmpty) {
      _remote = [];
      _remoteError = "Add at least one subreddit name.";
      return;
    }
    _fetchReddit(subreddits);
  }

  /// Links ending in "/" are folders (e.g. a PC sharing a wallpaper script's
  /// output with `python -m http.server`); every picture listed there is used.
  Future<void> _resolveWebLinks(List<String> urls) async {
    _remoteLoading = true;
    _remoteError = null;
    notifyListeners();

    final List<String> found = [];
    String? error;
    for (final String url in urls) {
      if (!url.endsWith("/")) {
        found.add(url);
        continue;
      }
      try {
        found.addAll(await _readFolderListing(Uri.parse(url)));
      } catch (e) {
        error = "Couldn't open $url ($e).";
      }
    }

    _remoteLoading = false;
    _remoteFetchedAt = DateTime.now();
    if (found.isEmpty) {
      _remote = [];
      _remoteError = error ?? "No pictures found at those links.";
    } else {
      found.shuffle(_random);
      _remote = found;
      _remotePosition = 0;
      _remoteError = error;
      _slideCounter++;
    }
    _onSettingsChanged();
    notifyListeners();
  }

  Future<List<String>> _readFolderListing(Uri folder) async {
    final HttpClient client = HttpClient()..connectionTimeout = const Duration(seconds: 15);
    try {
      final HttpClientRequest request = await client.getUrl(folder);
      request.headers.set(HttpHeaders.userAgentHeader, _userAgent);
      final HttpClientResponse response = await request.close().timeout(const Duration(seconds: 30));
      if (response.statusCode < 200 || response.statusCode >= 300) {
        throw HttpException("HTTP ${response.statusCode}");
      }
      final String html = await response.transform(utf8.decoder).join();
      final RegExp link = RegExp(r'''href\s*=\s*["']([^"']+\.(?:jpe?g|png|webp))["']''', caseSensitive: false);
      return {
        for (final Match match in link.allMatches(html)) folder.resolve(match.group(1)!).toString(),
      }.toList();
    } finally {
      client.close(force: true);
    }
  }

  static List<String> _splitList(String text) =>
      text.split(RegExp(r"[\s,;]+")).map((part) => part.trim()).where((part) => part.isNotEmpty).toList();

  static const String _userAgent = "android:app.yama.launcher:1.0 (YaMa Launcher wallpaper)";

  Future<void> _fetchReddit(List<String> subreddits) async {
    _remoteLoading = true;
    _remoteError = null;
    notifyListeners();

    // Reddit no longer serves its JSON listings to apps that aren't signed
    // in (HTTP 403), but its public RSS feeds still work.
    final String path = "/r/${subreddits.join("+")}/hot/.rss?limit=100";
    List<String> found = [];
    String? error;
    for (final String host in const ["www.reddit.com", "old.reddit.com"]) {
      try {
        found = await _readRedditFeed(Uri.parse("https://$host$path"));
        error = null;
        break;
      } catch (e) {
        error = "Couldn't reach Reddit ($e).";
      }
    }

    _remoteLoading = false;
    _remoteFetchedAt = DateTime.now();
    if (found.isEmpty) {
      _remoteError = error ?? "No pictures found in those subreddits.";
    } else {
      found.shuffle(_random);
      _remote = found;
      _remotePosition = 0;
      _remoteError = null;
      _slideCounter++;
    }
    _onSettingsChanged();
    notifyListeners();
  }

  /// Reads a subreddit RSS (Atom) feed and keeps direct picture links
  /// (i.redd.it and imgur). Tall pictures are skipped when they load.
  Future<List<String>> _readRedditFeed(Uri uri) async {
    final HttpClient client = HttpClient()..connectionTimeout = const Duration(seconds: 15);
    try {
      final HttpClientRequest request = await client.getUrl(uri);
      request.headers.set(HttpHeaders.userAgentHeader, _userAgent);
      request.headers.set(HttpHeaders.acceptHeader, "application/atom+xml, application/xml;q=0.9, */*;q=0.5");
      final HttpClientResponse response = await request.close().timeout(const Duration(seconds: 30));
      if (response.statusCode < 200 || response.statusCode >= 300) {
        throw HttpException("HTTP ${response.statusCode}");
      }
      final String feed = await response.transform(utf8.decoder).join();
      // Post bodies are HTML escaped inside the feed.
      final String text = feed
          .replaceAll("&quot;", '"')
          .replaceAll("&#34;", '"')
          .replaceAll("&lt;", "<")
          .replaceAll("&gt;", ">")
          .replaceAll("&amp;", "&");
      final RegExp picture = RegExp(
        r"""https://(?:i\.redd\.it|i\.imgur\.com)/[A-Za-z0-9_\-]+\.(?:jpe?g|png|webp)""",
        caseSensitive: false,
      );
      return {for (final Match match in picture.allMatches(text)) match.group(0)!}.toList();
    } finally {
      client.close(force: true);
    }
  }

  Future<void> _ensureFileExplorer() async {
    if (!await _fLauncherChannel.checkForGetContentAvailability()) {
      throw NoFileExplorerException();
    }
  }

  Future<void> pickWallpaper() async {
    await _ensureFileExplorer();

    final imagePicker = ImagePicker();
    final pickedFile = await imagePicker.pickImage(source: ImageSource.gallery);
    if (pickedFile != null) {
      Uint8List bytes = await pickedFile.readAsBytes();
      await _wallpaperFile!.writeAsBytes(bytes);

      _wallpaper = MemoryImage(bytes);
      await _settingsService.setValue(YamaKeys.wallpaperMode, WallpaperMode.image);
      notifyListeners();
    }
  }

  /// Sets the single wallpaper picture from a file chosen in YaMa's browser.
  Future<void> setWallpaperFromFile(String path) async {
    final Uint8List bytes = await File(path).readAsBytes();
    await _wallpaperFile!.writeAsBytes(bytes, flush: true);
    _wallpaper = MemoryImage(bytes);
    await _settingsService.setValue(YamaKeys.wallpaperMode, WallpaperMode.image);
    notifyListeners();
  }

  /// Copies every picture in a folder into the slideshow.
  Future<int> addSlideshowFolder(String folderPath) async {
    final Directory target = _slideshowDirectory!;
    if (!await target.exists()) {
      await target.create(recursive: true);
    }
    final List<File> pictures = Directory(folderPath)
        .listSync()
        .whereType<File>()
        .where((f) => RegExp(r"\.(jpe?g|png|webp|gif)$", caseSensitive: false).hasMatch(f.path))
        .toList();
    final int stamp = DateTime.now().millisecondsSinceEpoch;
    for (int i = 0; i < pictures.length; i++) {
      await pictures[i].copy("${target.path}/slide_${stamp}_$i");
    }
    await _loadSlides();
    _slideCounter++;
    await _settingsService.setValue(YamaKeys.wallpaperMode, WallpaperMode.slideshow);
    _onSettingsChanged();
    notifyListeners();
    return pictures.length;
  }

  /// Adds pictures to the slideshow and switches to slideshow mode.
  Future<int> addSlideshowPictures() async {
    await _ensureFileExplorer();

    final List<XFile> picked = await ImagePicker().pickMultiImage();
    if (picked.isEmpty) {
      return 0;
    }

    final Directory directory = _slideshowDirectory!;
    if (!await directory.exists()) {
      await directory.create(recursive: true);
    }
    final int stamp = DateTime.now().millisecondsSinceEpoch;
    for (int i = 0; i < picked.length; i++) {
      final Uint8List bytes = await picked[i].readAsBytes();
      await File("${directory.path}/slide_${stamp}_$i").writeAsBytes(bytes);
    }

    await _loadSlides();
    _slideCounter++;
    await _settingsService.setValue(YamaKeys.wallpaperMode, WallpaperMode.slideshow);
    _onSettingsChanged();
    notifyListeners();
    return picked.length;
  }

  Future<void> clearSlideshow() async {
    final Directory? directory = _slideshowDirectory;
    if (directory != null && await directory.exists()) {
      await directory.delete(recursive: true);
    }
    await _loadSlides();
    if (mode == WallpaperMode.slideshow) {
      await _settingsService.setValue(YamaKeys.wallpaperMode, WallpaperMode.gradient);
    }
    _onSettingsChanged();
    notifyListeners();
  }

  Future<void> setSolidColor(Color color) async {
    await _settingsService.setValue(YamaKeys.wallpaperSolidColor, color.value);
    await _settingsService.setValue(YamaKeys.wallpaperMode, WallpaperMode.solid);
    notifyListeners();
  }

  Future<void> setGradient(FLauncherGradient fLauncherGradient) async {
    final File? file = _wallpaperFile;
    if (file != null && await file.exists()) {
      await file.delete();
    }
    _wallpaper = null;

    await _settingsService.setGradientUuid(fLauncherGradient.uuid);
    await _settingsService.setValue(YamaKeys.wallpaperMode, WallpaperMode.gradient);
    notifyListeners();
  }

  /// Switches back to an already chosen picture or slideshow, if available.
  Future<void> useMode(WallpaperMode newMode) async {
    await _settingsService.setValue(YamaKeys.wallpaperMode, newMode);
    _onSettingsChanged();
    notifyListeners();
  }
}

class NoFileExplorerException implements Exception {}
